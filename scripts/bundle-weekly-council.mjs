/**
 * Bundle the weekly-council serverless function into a single ESM file.
 * Vercel's per-file TS compiler cannot follow src/domain without .js extensions;
 * the bundle is the function it actually runs.
 */
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

await build({
  absWorkingDir: root,
  entryPoints: [path.join(root, "api/_weeklyCouncil/vercel-entry.ts")],
  outfile: path.join(root, "api/_weeklyCouncil/dist/handler.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  logLevel: "info",
  banner: {
    js: "/* generated by scripts/bundle-weekly-council.mjs — do not edit */",
  },
});

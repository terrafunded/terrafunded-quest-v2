/**
 * Bundle the weekly-council serverless function into a single ESM file.
 * Vercel's per-file TS compiler cannot follow src/domain without .js extensions;
 * the bundle is the function it actually runs.
 */
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

async function bundle(entry, outfile) {
  await build({
    absWorkingDir: root,
    entryPoints: [path.join(root, entry)],
    outfile: path.join(root, outfile),
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    logLevel: "info",
    alias: { "@": path.join(root, "src") },
    banner: {
      js: "/* generated by scripts/bundle-weekly-council.mjs — do not edit */",
    },
  });
}

await bundle("api/_weeklyCouncil/vercel-entry.ts", "api/_weeklyCouncil/dist/handler.js");
await bundle("api/_nightlyExport/vercel-entry.ts", "api/_nightlyExport/dist/handler.js");
